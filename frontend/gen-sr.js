lines.push(`          music.coverUrl = coverUrl`);
lines.push(`          setCurrentMusic({ ...music })`);
lines.push(`          const img = new Image()`);
lines.push(`          img.crossOrigin = 'anonymous'`);
lines.push(`          img.onload = () => {`);
lines.push(`            const colors = extractColorsFromImage(img)`);
lines.push(`            setCoverColors(colors)`);
lines.push(`          }`);
lines.push(`          img.src = coverUrl`);
lines.push(`        }`);
lines.push(`      })`);
lines.push('');
lines.push(`      gdService.getLyric(item.lyricId, item.source).then((lyricData) => {`);
lines.push(`        if (lyricData.lyric) {`);
lines.push(`          const combined = lyricData.tlyric`);
lines.push(`            ? lyricData.lyric + '\n' + lyricData.tlyric`);
lines.push(`            : lyricData.lyric`);
lines.push(`          const parsed = LRCParser.parse(combined)`);
lines.push(`          setLyrics(parsed)`);
lines.push(`        }`);
lines.push(`      })`);
lines.push(`    } catch (err) {`);
lines.push(`      console.error('[Play]', err)`);
lines.push(`    } finally {`);
lines.push(`      setLoadingId(null)`);
lines.push(`    }`);
lines.push(`  }`);
lines.push('');
lines.push(`  return (`);
lines.push(`    <div className="px-6 pb-8 overflow-y-auto no-scrollbar flex-1">`);
lines.push(`      <p className="text-xs text-white/30 font-medium uppercase tracking-widest mb-4 px-1">`);
lines.push(`        搜索结果 · {results.length} 首`);
lines.push(`      </p>`);
lines.push(`      <AnimatePresence>`);
lines.push(`        <div className="space-y-1">`);
lines.push(`          {results.map((item, idx) => (`);
lines.push(`            <motion.div`);
lines.push(`              key={\`\${item.source}-\${item.id}\`}`);
lines.push(`              initial={{ opacity: 0, y: 20 }}`);
lines.push(`              animate={{ opacity: 1, y: 0 }}`);
lines.push(`              transition={{ delay: idx * 0.03, duration: 0.3 }}`);
lines.push(`              onClick={() => handlePlay(item)}`);
lines.push(`              className="flex items-center gap-4 px-4 py-3 rounded-2xl hover:bg-white/[0.06] cursor-pointer transition-all group"`);
lines.push(`            >`);
lines.push(`              <div className="w-12 h-12 rounded-xl bg-white/10 flex-shrink-0 overflow-hidden flex items-center justify-center">`);
lines.push(`                {loadingId === item.id ? (`);
lines.push(`                  <div className="w-5 h-5 border-2 border-white/20 border-t-white rounded-full animate-spin" />`);
lines.push(`                ) : (`);
lines.push(`                  <svg width="20" height="20" viewBox="0 0 24 24" fill="currentColor" className="text-white/30 group-hover:text-white/70 transition-colors">`);
lines.push(`                    <polygon points="5,3 19,12 5,21" />`);
lines.push(`                  </svg>`);
lines.push(`                )}`);
lines.push(`              </div>`);
lines.push(`              <div className="flex-1 min-w-0">`);
lines.push(`                <p className="text-sm font-semibold text-white truncate">{item.name}</p>`);
lines.push(`                <p className="text-xs text-white/40 truncate mt-0.5">`);
lines.push(`                  {item.artist.join(' / ')} · {item.album}`);
lines.push(`                </p>`);
lines.push(`              </div>`);
lines.push(`              <span className="text-[10px] text-white/20 font-mono px-2 py-1 rounded-md bg-white/5">`);
lines.push(`                {item.source}`);
lines.push(`              </span>`);
lines.push(`            </motion.div>`);
lines.push(`          ))}`);
lines.push(`        </div>`);
lines.push(`      </AnimatePresence>`);
lines.push(`    </div>`);
lines.push(`  )`);
lines.push(`}`);

