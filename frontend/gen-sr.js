const fs = require('fs');
const path = 'C:/Users/Colorful/Desktop/app/frontend/src/components/search/SearchResults.tsx';

const lines = [];
lines.push(`'use client'`);
lines.push('');
lines.push(`import { useState } from 'react'`);
lines.push(`import { motion, AnimatePresence } from 'framer-motion'`);
lines.push(`import { useSearchStore } from '@/stores/searchStore'`);
lines.push(`import { usePlayerStore } from '@/stores/playerStore'`);
lines.push(`import { useLyricStore } from '@/stores/lyricStore'`);
lines.push(`import { useUIStore } from '@/stores/uiStore'`);
lines.push(`import { gdService } from '@/services/gd-api.service'`);
lines.push(`import { LRCParser } from '@/lib/lrc-parser'`);
lines.push(`import { extractColorsFromImage } from '@/lib/color-thief'`);
lines.push(`import { Music } from '@/types'`);
lines.push('');
lines.push(`export function SearchResults() {`);
lines.push(`  const { results, isSearching, query } = useSearchStore()`);
lines.push(`  const { setCurrentMusic, setIsPlaying } = usePlayerStore()`);
lines.push(`  const { setLyrics } = useLyricStore()`);
lines.push(`  const { setCoverColors } = useUIStore()`);
lines.push(`  const [loadingId, setLoadingId] = useState<string | null>(null)`);
lines.push('');
lines.push(`  if (isSearching) {`);
lines.push(`    return (`);
lines.push(`      <div className="flex items-center justify-center py-20">`);
lines.push(`        <div className="w-8 h-8 border-2 border-white/20 border-t-white rounded-full animate-spin" />`);
lines.push(`      </div>`);
lines.push(`    )`);
lines.push(`  }`);
lines.push('');
lines.push(`  if (!query && results.length === 0) {`);
lines.push(`    return (`);
lines.push(`      <div className="flex flex-col items-center justify-center py-20 text-center">`);
lines.push(`        <svg width="48" height="48" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.5" className="text-white/20 mb-4">`);
lines.push(`          <circle cx="11" cy="11" r="8" /><line x1="21" y1="21" x2="16.65" y2="16.65" />`);
lines.push(`        </svg>`);
lines.push(`        <p className="text-white/30 text-sm font-medium">搜索你喜欢的音乐</p>`);
lines.push(`      </div>`);
lines.push(`    )`);
lines.push(`  }`);
lines.push('');
lines.push(`  if (results.length === 0 && query) {`);
lines.push(`    return (`);
lines.push(`      <div className="flex flex-col items-center justify-center py-20 text-center">`);
lines.push(`        <p className="text-white/40 text-lg font-semibold">未找到 "{query}" 的结果</p>`);
lines.push(`        <p className="text-white/20 text-sm mt-2">试试更换音乐源或关键词</p>`);
lines.push(`      </div>`);
lines.push(`    )`);
lines.push(`  }`);
lines.push('');
lines.push(`  const handlePlay = async (item: typeof results[0]) => {`);
lines.push(`    setLoadingId(item.id)`);
lines.push(`    try {`);
lines.push(`      const audioUrl = await gdService.getUrl(item.id, item.source, 320)`);
lines.push(`      if (!audioUrl) return`);
lines.push('');
lines.push(`      const music: Music = {`);
lines.push(`        id: \`\${item.source}-\${item.id}\`,`);
lines.push(`        title: item.name,`);
lines.push(`        artist: item.artist.join(' / '),`);
lines.push(`        album: item.album,`);
lines.push(`        coverUrl: null,`);
lines.push(`        audioUrl,`);
lines.push(`        duration: 0,`);
lines.push(`        playCount: 0,`);
lines.push(`        source: item.source,`);
lines.push(`        sourceId: item.id,`);
lines.push(`      }`);
lines.push(`      setCurrentMusic(music)`);
lines.push(`      setIsPlaying(true)`);
lines.push('');
lines.push(`      gdService.getPic(item.picId, item.source, 500).then((coverUrl) => {`);
